// Rada, kde notifikace povolit, podle systému a prohlížeče (navigator.userAgent): notifikace ukazuje systém a ten je
// může zahodit bez chyby (macOS: Google Chrome Helper (Alerts) / aplikace pro Safari, Soustředění, sdílení obrazovky;
// Windows: Nerušit).
// text(key, ...params) = překlad stránky. Ukazuje se pod tlačítkem Vyzkoušet notifikace hned, ne až po zkoušce
// Safari: stránky rozšíření mají adresu safari-web-extension:// – spolehlivé, ať se Safari identifikuje jakkoli.
// Jinak identifikace: "Version/27.2 Safari/605.1.15" bez "Chrome/" (Chrome má "Safari/537.36", ale ne "Version/")
function isSafariBrowser() {
  if (typeof location !== "undefined" && location.protocol === "safari-web-extension:") return true;
  const ua = navigator.userAgent;
  return /Version\/[\d.]+ Safari\//.test(ua) && !/Chrome\/|Chromium\/|Edg\/|OPR\//.test(ua);
}

function getNotificationHint(text) {
  const ua = navigator.userAgent;
  // Notifikace v Safari posílá aplikace AllyZap přes nativní most (safari/), v Oznámeních se povoluje ona
  if (isSafariBrowser()) return text("notifyHintSafari");
  const browser = /Firefox\//.test(ua) ? "Firefox" : /Edg\//.test(ua) ? "Microsoft Edge" : /OPR\//.test(ua) ? "Opera" : "Google Chrome";
  if (/Mac OS X/.test(ua)) return browser === "Google Chrome" ? text("notifyHintMacChrome") : text("notifyHintMac", browser);
  return /Windows/.test(ua) ? text("notifyHintWindows", browser) : text("notifyHintOther", browser);
}

// Výsledek tlačítka Vyzkoušet notifikace (nastavení i průvodce): result = odpověď služby na pozadí
// ({ sent, failed, error, level }), undefined = ještě nezkoušeno (jen rada), null = služba neodpověděla
function describeNotificationTest(result, text) {
  const hint = getNotificationHint(text);
  if (result === undefined) return { text: hint, error: false };
  if (!result) return { text: hint, error: true };
  if (result.level === "denied") return { text: text("testNotificationsDenied", hint), error: true };
  if (result.failed > 0) {
    const total = result.sent + result.failed;
    return { text: text("testNotificationsFailed", result.failed, total, result.error ? ` (${result.error})` : "", hint), error: true };
  }
  return { text: text("testNotificationsSent", hint), error: false };
}

// Safari: notifikace posílá aplikace AllyZap – pod radu tlačítko, které v Nastavení systému otevře rovnou její
// oznámení (zpráva aplikaci přes nativní most, SafariWebExtensionHandler). Jinde nic
function appendNotificationSettingsButton(output, text) {
  if (!isSafariBrowser() || typeof chrome?.runtime?.sendNativeMessage !== "function") return;
  const button = document.createElement("button");
  button.type = "button";
  button.className = "notify-settings-open";
  button.textContent = text("notifySettingsOpen");
  button.addEventListener("click", () => {
    chrome.runtime.sendNativeMessage("application.id", { type: "openNotificationSettings" }).catch((error) => console.error("Nastavení oznámení:", error));
  });
  // Vlastní řádek pod textem rady (styl přímo – stránka nastavení i průvodce)
  const row = document.createElement("span");
  row.className = "notify-settings-row";
  row.style.display = "block";
  row.style.marginTop = "8px";
  row.append(button);
  output.append(row);
}
